"""## 6. Funciones de Operación del Sistema ATMOS

Funciones que permiten usar el modelo con lecturas individuales, aplicar el temporizador externo y traducir la decisión a una acción simulada del aire acondicionado.

"""

# ==========================================
# CONFIGURACIÓN DE ACCIONES DEL AIRE ATMOS
# ==========================================

TEMP_MANTENER = 24
TEMP_ENFRIAR_MODERADO = 23
TEMP_ENFRIAR_FUERTE = 22

TIEMPO_ESPERA_APAGADO = 10  # minutos sin presencia antes de apagar


# ==========================================
# 1. FUNCIÓN PARA PREDECIR UNA SOLA LECTURA
# ==========================================

def predecir_lectura(modelo, presencia, temp_ambiente, temp_ac, humedad):
    """
    Recibe una lectura individual de sensores y devuelve la decisión del modelo ML.
    """

    delta_t = temp_ambiente - temp_ac

    lectura = pd.DataFrame([{
        'presencia': presencia,
        'temp_ambiente': temp_ambiente,
        'temp_ac': temp_ac,
        'delta_t': delta_t,
        'humedad': humedad
    }])

    decision_ml = modelo.predict(lectura)[0]

    return decision_ml, delta_t


# ==================================================
# 2. FUNCIÓN DE TEMPORIZADOR FUERA DEL MODELO ML
# ==================================================

def aplicar_temporizador(decision_ml, presencia, minutos_sin_presencia):
    """
    Aplica la lógica de espera antes de apagar el aire.
    Esta función NO pertenece al modelo ML.
    Es una capa de control del sistema.
    """

    if presencia == 0 and decision_ml == 'apagar':

        if minutos_sin_presencia >= TIEMPO_ESPERA_APAGADO:
            return 'apagar'

        else:
            return 'esperar_apagado'

    return decision_ml


# ==================================================
# 3. FUNCIÓN PARA TRADUCIR DECISIÓN A ACCIÓN DEL AC
# ==================================================

def traducir_decision_ac(decision_final, temp_ambiente):
    """
    Traduce la decisión final del sistema en una acción entendible para el AC.
    Por ahora es una simulación, no envía señal IR real.
    """

    if decision_final == 'apagar':
        return {
            'estado_ac': 'apagado',
            'temperatura_objetivo': None,
            'modo': 'off',
            'ventilacion': 'apagada',
            'accion': 'Enviar comando IR para apagar el aire acondicionado'
        }

    elif decision_final == 'esperar_apagado':
        return {
            'estado_ac': 'encendido',
            'temperatura_objetivo': 'sin cambio',
            'modo': 'sin cambio',
            'ventilacion': 'sin cambio',
            'accion': 'No enviar nuevo comando. Esperar hasta cumplir los 10 minutos sin presencia'
        }

    elif decision_final == 'mantener':
        return {
            'estado_ac': 'encendido',
            'temperatura_objetivo': TEMP_MANTENER,
            'modo': 'cool',
            'ventilacion': 'automatica',
            'accion': f'Mantener el aire acondicionado en {TEMP_MANTENER}°C'
        }

    elif decision_final == 'enfriar_fuerte':

        if temp_ambiente >= 30:
            temperatura = TEMP_ENFRIAR_FUERTE
            ventilacion = 'alta'
        else:
            temperatura = TEMP_ENFRIAR_MODERADO
            ventilacion = 'media'

        return {
            'estado_ac': 'encendido',
            'temperatura_objetivo': temperatura,
            'modo': 'cool',
            'ventilacion': ventilacion,
            'accion': f'Configurar el aire a {temperatura}°C con ventilación {ventilacion}'
        }

"""## 7. Módulo de Detección de Fallas del AC

Regla lógica independiente del modelo ML para identificar posible bajo rendimiento del aire acondicionado.

"""

# ==========================================
# MÓDULO DE DETECCIÓN DE FALLAS DEL AC
# ==========================================

TIEMPO_MINIMO_FALLA = 30          # minutos en enfriar_fuerte antes de evaluar falla
DESCENSO_MINIMO_ESPERADO = 3      # °C que debería bajar el salón
TEMP_AC_ALTA = 23                 # si el aire sale a 23°C o más, puede indicar bajo rendimiento


def detectar_falla_ac(decision_final, minutos_enfriando, temp_inicio, temp_actual, temp_ac_actual):
    """
    Evalúa si el aire acondicionado podría estar fallando.

    Esta lógica se activa solo cuando el sistema lleva cierto tiempo en 'enfriar_fuerte'.
    Si después de 30 minutos la temperatura ambiente no baja al menos 3°C,
    se genera una alerta de posible falla o bajo rendimiento.
    """

    # Si el sistema no está en enfriar_fuerte, no se evalúa falla
    if decision_final != 'enfriar_fuerte':
        return {
            'estado_falla': 'no_aplica',
            'alerta': False,
            'mensaje': 'No se evalúa falla porque el sistema no está en modo enfriar_fuerte.'
        }

    # Si todavía no han pasado 30 minutos, solo se sigue monitoreando
    if minutos_enfriando < TIEMPO_MINIMO_FALLA:
        return {
            'estado_falla': 'monitoreando',
            'alerta': False,
            'mensaje': f'El sistema lleva {minutos_enfriando} minutos enfriando. Aún no se evalúa falla.'
        }

    # Calcular cuánto bajó la temperatura ambiente
    descenso_temp = temp_inicio - temp_actual

    # Caso de posible falla
    if descenso_temp < DESCENSO_MINIMO_ESPERADO:
        if temp_ac_actual >= TEMP_AC_ALTA:
            mensaje = (
                f'Posible falla del AC: después de {minutos_enfriando} minutos en enfriar_fuerte, '
                f'la temperatura solo bajó {descenso_temp:.1f}°C y el aire del AC sale a {temp_ac_actual}°C.'
            )
        else:
            mensaje = (
                f'Posible bajo rendimiento: después de {minutos_enfriando} minutos en enfriar_fuerte, '
                f'la temperatura solo bajó {descenso_temp:.1f}°C.'
            )

        return {
            'estado_falla': 'posible_falla',
            'alerta': True,
            'descenso_temperatura': round(descenso_temp, 2),
            'mensaje': mensaje
        }

    # Caso normal: sí bajó lo suficiente
    return {
        'estado_falla': 'funcionamiento_normal',
        'alerta': False,
        'descenso_temperatura': round(descenso_temp, 2),
        'mensaje': f'El AC funciona correctamente. La temperatura bajó {descenso_temp:.1f}°C.'
    }

