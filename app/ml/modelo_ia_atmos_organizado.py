# PARÁMETROS DE DECISIÓN ATMOS

LIMITE_CALOR_MODERADO = 28
LIMITE_CALOR_FUERTE = 30
LIMITE_HUMEDAD_ALTA = 70
DELTA_MINIMO_ESPERADO = 6
TEMP_AC_POCO_FRIA = 22

# FUNCIÓN DE DECISIÓN MEJORADA

def decidir(row):
    # 1. Si no hay personas, se recomienda apagar
    if row['presencia'] == 0:
        return 'apagar'

    # 2. Si hay presencia y el salón está demasiado caliente,
    # se recomienda enfriar fuerte directamente
    if row['temp_ambiente'] >= LIMITE_CALOR_FUERTE:
        return 'enfriar_fuerte'

    # 3. Si hay presencia y calor moderado, no basta con una sola señal.
    # Se cuentan señales adicionales para evitar enfriar fuerte innecesariamente.
    if row['temp_ambiente'] >= LIMITE_CALOR_MODERADO:

        señales_calor = 0

        # Señal 1: humedad alta
        if row['humedad'] >= LIMITE_HUMEDAD_ALTA:
            señales_calor += 1

        # Señal 2: poca diferencia entre temperatura ambiente y temperatura del AC
        if row['delta_t'] < DELTA_MINIMO_ESPERADO:
            señales_calor += 1

        # Señal 3: el aire del AC no está saliendo suficientemente frío
        if row['temp_ac'] >= TEMP_AC_POCO_FRIA:
            señales_calor += 1

        # Para enfriar fuerte en calor moderado,
        # se requieren al menos 2 señales adicionales
        if señales_calor >= 2:
            return 'enfriar_fuerte'
        else:
            return 'mantener'

    # 4. Si hay presencia, pero no hay calor suficiente,
    # se mantiene el funcionamiento normal
    return 'mantener'

df['decision'] = df.apply(decidir, axis=1)
